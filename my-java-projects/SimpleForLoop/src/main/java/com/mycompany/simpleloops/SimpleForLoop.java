package com.mycompany.simpleloops;

/**
 *
 * @author oyini
 */
public class SimpleForLoop{

    public static void main(String[] args) {
        int count;
        for (count=10; count<=50 ; count++){
            System.out.println(count);
        }
        count=1;
        while(count <=10){
            System.out.println(count);
            count++;
        }
        
        do {
            System.out.println(count);
            count++;
            
        }while(count<=10);
              
            
    }
}
